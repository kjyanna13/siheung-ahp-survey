def pairs(n):
    """0..n-1 조합을 항상 같은 순서로 돌려준다."""
    return list(combinations(range(n), 2))


def blocks(field):
    """[(블록코드, 블록제목, 안내문, [항목코드…], [항목라벨…])]

    항목코드는 전략 블록이면 S1·S2…, 과제 블록이면 과제코드.
    """
    goal = FIELD_GOAL[field]
    out = []
    if field in FLAT:
        codes = [c for c, v in TASKS.items() if v[0] == field]
        labels = [TASKS[c][1] for c in codes]
        out.append(("FLAT",
                    f"{field} 핵심과제 {len(codes)}개 간 비교",
                    f"{field} 분야의 목표 「{goal}」를 달성하는 데 "
                    "두 과제 중 어느 쪽이 더 중요합니까?",
                    codes, labels))
        return out

    strat = STRAT[field]
    if len(strat) >= 2:
        out.append(("STRAT",
                    f"{field} 전략 {len(strat)}개 간 비교",
                    f"{field} 분야의 목표 「{goal}」를 달성하는 데 "
                    "두 전략 중 어느 쪽이 더 중요합니까?",
                    [c for c, _n, _t in strat],
                    [n for _c, n, _t in strat]))
    for code, name, ts in strat:
        if len(ts) < 2:
            continue
        out.append((code,
                    f"{name} — 핵심과제 {len(ts)}개 간 비교",
                    f"「{name}」 전략을 실현하는 데 두 과제 중 어느 쪽이 더 중요합니까?",
                    ts, [TASKS[t][1] for t in ts]))
    return out


def block_stats(field):
    bs = blocks(field)
    return len(bs), sum(len(pairs(len(b[3]))) for b in bs)
